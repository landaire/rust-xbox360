#!/usr/bin/env python3
"""Writes sysroot/crates.bzl, the standard library crate graph for the
Xbox 360 target.

Usage: update_sysroot.py UNIT_GRAPH LIBRARY_CARGO_LOCK

UNIT_GRAPH is Cargo's unit graph of a std title, built against the overlaid
library source of the pinned release. From examples/stdhello, with the
overlay copied into rustup's rust-src of that release:

    RUSTC_BOOTSTRAP=1 cargo build --release -Zjson-target-spec \\
        -Zunstable-options --unit-graph > unit-graph.json

LIBRARY_CARGO_LOCK is library/Cargo.lock of the same source; it supplies the
checksums of the crates.io dependencies.
"""

import json
import sys
import tomllib
from pathlib import Path, PurePosixPath

OUTPUT = Path(__file__).resolve().parent.parent / "sysroot" / "crates.bzl"
LIBRARY_MARKER = "/lib/rustlib/src/rust/library/"
REGISTRY_ID = "registry+https://github.com/rust-lang/crates.io-index"


class GraphError(Exception):
    pass


def package_key(pkg_id):
    """`name@version` of a Cargo package id."""
    source, _, rest = pkg_id.partition("#")
    if "@" in rest:
        return rest
    # Path packages whose directory name is the package name omit it.
    name = PurePosixPath(source).name
    return f"{name}@{rest}"


def library_relative(path):
    index = path.find(LIBRARY_MARKER)
    if index < 0:
        raise GraphError(f"{path} is not inside the Rust library source")
    return path[index + len(LIBRARY_MARKER):]


def registry_relative(path, name, version):
    marker = f"/{name}-{version}/"
    index = path.find(marker)
    if index < 0:
        raise GraphError(f"{path} is not inside the {name} {version} package")
    return path[index + len(marker):]


def source_relative(unit, name, version):
    path = unit["target"]["src_path"]
    if unit["pkg_id"].startswith(REGISTRY_ID):
        return registry_relative(path, name, version)
    return library_relative(path)


def load_checksums(lock_path):
    with open(lock_path, "rb") as lock_file:
        lock = tomllib.load(lock_file)
    return {
        f"{package['name']}@{package['version']}": package["checksum"]
        for package in lock["package"]
        if "checksum" in package
    }


def crates(units, checksums):
    target_units = [u for u in units if u.get("platform") is not None]
    libraries = {}
    for unit in target_units:
        if unit["mode"] != "build" or not set(unit["target"]["kind"]) & {"lib", "rlib"}:
            continue
        key = package_key(unit["pkg_id"])
        name, _, version = key.partition("@")
        registry = unit["pkg_id"].startswith(REGISTRY_ID)
        if registry and key not in checksums:
            raise GraphError(f"library Cargo.lock has no checksum for {key}")
        deps = {}
        build_script = None
        for dep in unit["dependencies"]:
            dep_unit = units[dep["index"]]
            if dep_unit["mode"] == "run-custom-build":
                compile_unit = units[dep_unit["dependencies"][0]["index"]]
                build_script = {
                    "edition": compile_unit["target"]["edition"],
                    "root": source_relative(compile_unit, name, version),
                }
            else:
                deps[dep["extern_crate_name"]] = package_key(dep_unit["pkg_id"])
        libraries[key] = {
            "build_script": build_script,
            "crate": unit["target"]["name"].replace("-", "_"),
            "deps": dict(sorted(deps.items())),
            "edition": unit["target"]["edition"],
            "features": sorted(unit["features"]),
            "name": name,
            "registry_sha256": checksums[key] if registry else None,
            "root": source_relative(unit, name, version),
            "version": version,
        }
    return dict(sorted(libraries.items()))


def render(libraries):
    lines = [
        '"""Standard library crates for the Xbox 360 target.',
        "",
        "Generated by buck/update_sysroot.py; do not edit.",
        '"""',
        "",
        "# name@version -> crate. `root` and `build_script.root` are relative",
        "# to the library directory, or to the package for crates.io crates",
        "# (those with `registry_sha256`).",
        "SYSROOT_CRATES = " + json.dumps(libraries, indent = 4).replace("null", "None") + "",
    ]
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__.strip())
    with open(sys.argv[1], encoding="utf-8") as graph_file:
        graph = json.load(graph_file)
    try:
        libraries = crates(graph["units"], load_checksums(sys.argv[2]))
    except GraphError as error:
        raise SystemExit(f"error: {error}") from None
    OUTPUT.write_text(render(libraries), encoding="utf-8")


if __name__ == "__main__":
    main()
