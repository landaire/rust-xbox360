#!/usr/bin/env python3
"""Writes rust_release.bzl, the Rust archives Buck2 downloads.

Reads the release from the `channel` of rust-toolchain.toml, then records
the URL and SHA-256 of each component archive for each supported host, and
of the library source, from
https://static.rust-lang.org/dist/channel-rust-<release>.toml. Run it after
changing the channel.

With --check, only verifies that rust_release.bzl was generated for the
channel of each given rust-toolchain.toml (default: this repository's), so
that a project using this cell can confirm its rustup pin matches.
"""

import argparse
import ast
import re
import sys
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUST_TOOLCHAIN_TOML = HERE.parent / "rust-toolchain.toml"
OUTPUT = HERE / "rust_release.bzl"
DIST_URL = "https://static.rust-lang.org/dist"
# Only an exact release pins the same archives for rustup and Buck2;
# `stable` or `1.98` would move for rustup but not for Buck2.
RELEASE_PATTERN = re.compile(r"\d+\.\d+\.\d+")

# Components that Buck2 may run: rustc and rustdoc, the host standard
# library, clippy-driver, Cargo for bootstrapping a source-built compiler,
# and the LLVM tools bundled with the release.
COMPONENTS = ["rustc", "rust-std", "clippy-preview", "cargo", "llvm-tools-preview"]

# Buck2 `prelude//os` and `prelude//cpu` constraint names to Rust host
# triples.
HOSTS = {
    "linux": {
        "arm64": "aarch64-unknown-linux-gnu",
        "x86_64": "x86_64-unknown-linux-gnu",
    },
    "macos": {
        "arm64": "aarch64-apple-darwin",
        "x86_64": "x86_64-apple-darwin",
    },
    "windows": {
        "arm64": "aarch64-pc-windows-msvc",
        "x86_64": "x86_64-pc-windows-msvc",
    },
}


def archive(manifest, component, triple):
    entry = manifest["pkg"][component]["target"][triple]
    if not entry.get("available", False):
        raise SystemExit(f"error: {component} is not available for {triple}")
    return entry["xz_url"], entry["xz_hash"]


def render(version, manifest, compiler_src_url, compiler_src_sha256):
    src_url, src_sha256 = archive(manifest, "rust-src", "*")
    lines = [
        '"""Rust archives that Buck2 downloads.',
        "",
        f"Generated by update_rust_release.py for Rust {version}; do not edit.",
        '"""',
        "",
        f'RUST_RELEASE = "{version}"',
        "",
        "# Library source of the release, the same for every host.",
        "RUST_SRC = {",
        f'    "sha256": "{src_sha256}",',
        f'    "url": "{src_url}",',
        "}",
        "",
        "# Complete compiler source, used only by the optional custom toolchain.",
        "RUST_COMPILER_SRC = {",
        f'    "sha256": "{compiler_src_sha256}",',
        f'    "url": "{compiler_src_url}",',
        "}",
        "",
        "# os -> cpu -> host triple and component archives.",
        "RUST_HOSTS = {",
    ]
    for os_name, cpus in HOSTS.items():
        lines.append(f'    "{os_name}": {{')
        for cpu, triple in cpus.items():
            lines.append(f'        "{cpu}": {{')
            lines.append(f'            "triple": "{triple}",')
            lines.append('            "archives": {')
            for component in COMPONENTS:
                url, sha256 = archive(manifest, component, triple)
                lines.append(f'                "{component}": {{')
                lines.append(f'                    "sha256": "{sha256}",')
                lines.append(f'                    "url": "{url}",')
                lines.append("                },")
            lines.append("            },")
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def pinned_release(toolchain_toml):
    with open(toolchain_toml, "rb") as toolchain_file:
        channel = tomllib.load(toolchain_file)["toolchain"]["channel"]
    if not RELEASE_PATTERN.fullmatch(channel):
        raise SystemExit(f"error: {toolchain_toml} channel {channel!r} is not an exact release")
    return channel


def generated_release():
    for node in ast.parse(OUTPUT.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and [t.id for t in node.targets if isinstance(t, ast.Name)] == ["RUST_RELEASE"]:
            return ast.literal_eval(node.value)
    raise SystemExit(f"error: {OUTPUT} does not assign RUST_RELEASE")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify rust_release.bzl without downloading")
    parser.add_argument(
        "toolchain_files",
        nargs="*",
        type=Path,
        metavar="RUST_TOOLCHAIN_TOML",
        help="with --check, the rust-toolchain.toml files to compare (default: this repository's)",
    )
    args = parser.parse_args()

    if not args.check:
        if args.toolchain_files:
            parser.error("rust-toolchain.toml arguments require --check")
        version = pinned_release(RUST_TOOLCHAIN_TOML)
        with urllib.request.urlopen(f"{DIST_URL}/channel-rust-{version}.toml", timeout=60) as response:
            manifest = tomllib.load(response)
        compiler_src_url = (
            f"{DIST_URL}/{manifest['date']}/rustc-{version}-src.tar.xz"
        )
        with urllib.request.urlopen(compiler_src_url + ".sha256", timeout=60) as response:
            compiler_src_sha256 = response.read().decode().split()[0]
        OUTPUT.write_text(
            render(version, manifest, compiler_src_url, compiler_src_sha256),
            encoding="utf-8",
        )
        return 0

    generated = generated_release()
    status = 0
    for toolchain_toml in args.toolchain_files or [RUST_TOOLCHAIN_TOML]:
        version = pinned_release(toolchain_toml)
        if generated != version:
            print(f"error: {OUTPUT} is for Rust {generated}, {toolchain_toml} pins {version}", file=sys.stderr)
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
