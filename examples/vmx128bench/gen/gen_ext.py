#!/usr/bin/env python3
"""Writes ext_table.rs: the assembly includes, symbol declarations and the
EXT_KERNELS table of the compiler-comparison kernels.

    python3 gen/gen_ext.py OUT.rs

Variants (symbol prefix: compiler, source, flags):
    msvc  cl.exe 16.00 /O2, kernels.c (SDK)
    l2v   clang -O2, kernels.c, VMX128
    l3v   clang -O3, kernels.c, VMX128
    lfv   clang -O3 -ffast-math, kernels.c, VMX128
    l3a   clang -O3 -mno-vmx128 (classic AltiVec), kernels.c
    lfa   clang -O3 -ffast-math -mno-vmx128, kernels.c
    l3s   clang -O3 -mno-altivec (scalar), kernels.c
    cv/ca/cs  clang -O3 -ffast-math, speed.c: VMX128 / classic / scalar
    rv/ra/rs  rustc -O3 kernels.rs: +vmx128 / -vmx128 / -altivec,-vmx128
The assembly files src/ext/c_*.s and src/ext/r_*.s come from cmp/make.sh.
"""

import sys

C_AUTOVEC = ["l2v", "l3v", "lfv", "l3a", "lfa", "l3s"]
C_SPEED = ["cv", "ca", "cs"]
RUST = ["rv", "ra", "rs"]

# kernels.c: (name, setup, ret)
AUTOVEC = [
    ("k_saxpy", "yxan", "None"), ("k_saxpy_r", "yxan", "None"),
    ("k_scale_inplace", "yan", "None"), ("k_add_f32_r", "cabn", "None"),
    ("k_mul_f32_r", "cabn", "None"), ("k_sum_f32", "xn", "Float"),
    ("k_dot_f32", "abn", "Float"), ("k_sum_i32", "xn", "Int"),
    ("k_dot_i16", "abn", "Int"), ("k_max_f32", "xn", "Float"),
    ("k_add_i32", "cabn", "None"), ("k_add_i32_r", "cabn", "None"),
    ("k_add_i16_r", "cabn", "None"), ("k_add_u8_r", "cabn", "None"),
    ("k_avg_u8_r", "cabn", "None"), ("k_addsat_u8_r", "cabn", "None"),
    ("k_and_u32_r", "cabn", "None"), ("k_shl_i32_r", "yxn", "None"),
    ("k_mul_i32_r", "cabn", "None"), ("k_min_f32_r", "cabn", "None"),
    ("k_max_i32_r", "cabn", "None"), ("k_clamp_f32_r", "clamp", "None"),
    ("k_clamp_i16_r", "yxn", "None"), ("k_abs_f32_r", "yxn", "None"),
    ("k_abs_i32_r", "yxn", "None"), ("k_f2i_r", "yxn", "None"),
    ("k_i2f_r", "yxn", "None"), ("k_u8_to_f32_r", "yxn", "None"),
    ("k_mat4_vec4_r", "mat4", "None"), ("k_copy_u32_r", "yxn", "None"),
    ("k_copy_u8", "yxn", "None"), ("k_set_u32", "dvn", "None"),
    ("k_set_f32", "yan", "None"), ("k_zero_u8", "dn", "None"),
    ("k_stride2_f32_r", "yxn", "None"), ("k_gather_f32_r", "gather", "None"),
    ("k_offset1_f32_r", "yxn", "None"), ("k_fir3_f32_r", "yxn", "None"),
    ("k_prefix_f32", "dn", "None"), ("k_g_add_f32", "none", "None"),
    ("k_g_saxpy", "g_a", "None"), ("k_g_add_i32", "none", "None"),
    ("k_g_dot", "none", "Float"), ("k_add16_f32_r", "cabn", "None"),
]

# speed.c / kernels.rs sp_*: (name, setup, ret, aligned_only, min_n, vmx128 only)
SPEED = []
for op, setup, ret in [("saxpy", "yxan", "None"), ("dot", "abn", "Float"), ("copy", "yxn", "None"),
                       ("bright", "yxn", "None"), ("u8f", "yxn", "None"), ("f2u8", "yxn", "None")]:
    SPEED.append(("sp_%s_s" % op, setup, ret, False, 16, False))
    SPEED.append(("sp_%s_v" % op, setup, ret, True, 16, False))
SPEED += [
    ("sp_mat4_s", "mat4", "None", False, 16, False),
    ("sp_mat4_v", "mat4", "None", True, 16, False),
    ("sp_mat4_v8", "mat4", "None", True, 1024, False),
    ("sp_mat4_v16", "mat4", "None", True, 1024, False),
    ("sp_mat4_x", "mat4", "None", True, 16, True),
]
GLOBAL_PREFIXES = ["msvc"] + C_AUTOVEC + RUST
GLOBAL_ARRAYS = ["g_a", "g_b", "g_c", "g_ia", "g_ib", "g_ic"]


def input_type(name):
    if name == "k_clamp_f32_r":
        return "FloatClamp"
    if name == "k_clamp_i16_r":
        return "ShortClamp"
    if name == "k_shl_i32_r":
        return "Shift"
    if name in ("k_dot_i16", "k_add_i16_r"):
        return "Short"
    if name in ("k_sum_i32", "k_add_i32", "k_add_i32_r", "k_mul_i32_r",
                "k_max_i32_r", "k_abs_i32_r", "k_i2f_r"):
        return "Int"
    if name in ("k_add_u8_r", "k_avg_u8_r", "k_addsat_u8_r", "k_u8_to_f32_r",
                "k_copy_u8", "k_zero_u8", "sp_bright_s", "sp_bright_v",
                "sp_u8f_s", "sp_u8f_v"):
        return "Byte"
    if name in ("k_and_u32_r", "k_copy_u32_r", "k_set_u32", "sp_copy_s", "sp_copy_v"):
        return "Word"
    if name == "k_mat4_vec4_r" or name.startswith("sp_mat4_"):
        return "PositiveFloat"
    return "Float"



def main():
    entries = []  # (symbol, base, setup, ret, aligned_only, min_n)
    for name, setup, ret in AUTOVEC:
        for p in GLOBAL_PREFIXES:
            entries.append(("%s_%s" % (p, name), name, setup, ret, name.startswith("k_g_"), 16))
    for name, setup, ret, aligned, min_n, x in SPEED:
        for p in C_SPEED + RUST:
            if x and p not in ("cv", "rv"):
                continue
            entries.append(("%s_%s" % (p, name), name, setup, ret, aligned, min_n))
    o = ["// Generated by gen/gen_ext.py. Do not edit.", ""]
    for f in ["msvc_kernels", "msvc_runtime"] + ["c_" + p for p in C_AUTOVEC + C_SPEED] + ["r_" + p for p in RUST]:
        o.append('core::arch::global_asm!(include_str!("ext/%s.s"), options(raw));' % f)
    o += ["", 'unsafe extern "C" {']
    o += ["    fn %s();" % e[0] for e in entries]
    for p in GLOBAL_PREFIXES:
        for j, name in enumerate(GLOBAL_ARRAYS):
            ty = "f32" if j < 3 else "i32"
            o.append("    static mut %s_%s: [%s; 1024];" % (p, name, ty))
    o += ["}", ""]
    for p in GLOBAL_PREFIXES:
        o.append("fn globals_%s() -> [u32; 6] {" % p)
        o.append("    // SAFETY: only forms addresses of the linked global arrays.")
        o.append("    unsafe { [%s] }" % ", ".join(
            "(&raw mut %s_%s) as usize as u32" % (p, name) for name in GLOBAL_ARRAYS))
        o += ["}", ""]
    o.append("pub static EXT_KERNELS: &[ExtKernel] = &[")
    for sym, name, setup, ret, aligned, min_n in entries:
        reference = "msvc_" + name if name.startswith("k_") else "cs_sp_%s_s" % name.split("_")[1]
        globals_fn = "Some(globals_%s)" % sym.split("_")[0] if name.startswith("k_g_") else "None"
        fixed_n = "Some(1024)" if name.startswith("k_g_") else "Some(16)" if name == "k_add16_f32_r" else "None"
        o.append("    ExtKernel { name: \"%s\", base: \"%s\", reference: \"%s\", input: Input::%s, "
                 "globals: %s, f: %s, setup: %s, ret: Ret::%s, aligned_only: %s, min_n: %d, fixed_n: %s }," % (
                     sym, name, reference, input_type(name), globals_fn, sym, setup, ret,
                     "true" if aligned else "false", min_n, fixed_n))
    o.append("];")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
